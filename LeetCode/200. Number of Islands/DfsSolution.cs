namespace LeetCode._200._Number_of_Islands;

public class DfsSolution
{
    public int NumIslands(char[][] grid)
    {
        int m = grid.Length;
        int n = grid[0].Length;
        int count = 0;
        for (int i = 0; i < m; i++)
        {
            for (int j = 0; j < n; j++)
            {
                if (grid[i][j] == '1')
                {
                    count++;
                    Dfs(i, j);
                }
            }
        }
        return count;

        void Dfs(int i, int j)
        {
            if (i < 0 || j < 0 || i >= m || j >= n || grid[i][j] == '0')
            {
                return;
            }
            grid[i][j] = '0';
            Dfs(i + 1, j);
            Dfs(i, j + 1);
            Dfs(i - 1, j);
            Dfs(i, j - 1);
        }
    }
}

